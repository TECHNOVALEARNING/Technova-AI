// Builds the migration that installs the official Registry items from drizzle/registry/.
// Usage: node scripts/build-registry-migration.mjs  →  drizzle/migrations/0032_registry_official_items.sql
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../drizzle/registry/", import.meta.url);
const items = JSON.parse(readFileSync(new URL("manifest.json", dir), "utf8"));

const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;
function dollar(body) {
  let tag = "tn";
  while (body.includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${body}$${tag}$`;
}

const rows = items.map((it) => {
  const content = readFileSync(new URL(it.file, dir), "utf8");
  if (content.length > 60000) throw new Error(`${it.file} exceeds 60 000 characters`);
  const ext = it.file.split(".").pop();
  return `(${quote(it.id)}, NULL, ${quote(it.title)}, ${quote(it.description)}, ${quote(it.category)}, ${dollar(content)}, ${quote(ext)}, ${quote(it.source ?? "TechNova")}, 'TechNova Studio', ${quote(it.license ?? "technova")}, true, true, true, false, 'public')`;
});

const sql = `-- Official Registry items (generated by scripts/build-registry-migration.mjs from drizzle/registry/).
-- Original TechNova designs: landing pages, page templates, sections, UI kits, font pairings (SIL OFL fonts),
-- animations, prompts and workflows. Re-runnable: rows are upserted by fixed id.
-- Rollback:
--   DELETE FROM public.registry_items WHERE id IN (${items.map((i) => quote(i.id)).join(", ")});

INSERT INTO public.registry_items (id, owner_id, title, description, category, content, file_ext, source, author, license, commercial_use, modification, redistribution, attribution_required, visibility)
VALUES
${rows.join(",\n")}
ON CONFLICT (id) DO UPDATE SET
  title = EXCLUDED.title, description = EXCLUDED.description, category = EXCLUDED.category, content = EXCLUDED.content,
  file_ext = EXCLUDED.file_ext, source = EXCLUDED.source, author = EXCLUDED.author, license = EXCLUDED.license,
  commercial_use = EXCLUDED.commercial_use, modification = EXCLUDED.modification, redistribution = EXCLUDED.redistribution,
  attribution_required = EXCLUDED.attribution_required, visibility = EXCLUDED.visibility, updated_at = now();
`;
writeFileSync(new URL("../drizzle/migrations/0032_registry_official_items.sql", import.meta.url), sql);
console.log(`${items.length} items written`);
